/* Real DOM smoke test for deployed admin.html and admin.js.
 * Run with: npm install --no-save jsdom@26 && node deployment/test-admin-repair-browser.cjs
 */
const fs=require('fs');
const assert=require('assert');
const {JSDOM}=require('jsdom');
const prefix=process.env.ADMIN_REPAIR_ASSETS||'/tmp/admin-repair-browser';
const html=fs.readFileSync(prefix+'/admin.html','utf8');
const js=fs.readFileSync(prefix+'/admin.js','utf8');
const dom=new JSDOM(html,{url:'https://example.test/admin',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
const requests=[];
const defaults={
  settings:{maintenance:false,default_rulebook:'Rules'},
  funds:{history:[],players:[{student_id:'2101',display_name:'Example',cash:'100'}]},
  'funds-extra':{history:[]},slots:{slots:[]}
};
const success=(body)=>({ok:true,status:200,json:async()=>body});
w.fetch=async(url,options={})=>{
 const path=url.split('/').pop(),body=options.body?JSON.parse(options.body):null;
 requests.push({path,body,method:options.method});
 if(path==='funds-extra'&&body?.action==='preview'){
  return success({kind:'forgive',total:'300',count:1,digest:'a'.repeat(64),people:[]});
 }
 if(path==='funds-extra'&&body?.action==='apply'){
  return success({kind:'forgive',total:'300',count:1});
 }
 if(path==='slots'&&body?.operation==='add'){
  defaults.slots={slots:[{student_id:body.student_id,class_number:body.class_number,display_name:null}]};
  return success({student_id:body.student_id,class_number:body.class_number});
 }
 return success(defaults[path]||{});
};
w.TeruNumber={
 fmt:v=>String(v),
 parseWhole:v=>/^\d+$/.test(String(v))?BigInt(v):null
};
w.crypto.randomUUID=()=>('abcdefff-1111-4444-8888-111111111111');
w.confirm=()=>true;
const fail=[];
w.addEventListener('error',e=>fail.push(e.error?.stack||e.message));
w.eval(js);
const tick=()=>new Promise(resolve=>setTimeout(resolve,25));
async function main(){
 await tick();
 assert.deepStrictEqual(fail,[],fail.join('\n'));
 // Existing "extra slots" control must be in the document, including when
 // the management section is initially collapsed.
 assert(d.querySelector('#extra-slot-form'), 'extra slot form missing');
 d.querySelector('#extra-slots-section').open=true;
 d.querySelector('#extra-slot-id').value='2999';
 d.querySelector('#extra-slot-class').value='3';
 let form=d.querySelector('#extra-slot-form');
 const submit=form.querySelector('button[type=submit]');
 form.dispatchEvent(new w.SubmitEvent('submit',{bubbles:true,cancelable:true,submitter:submit}));
 await tick();
 const created=requests.find(x=>x.path==='slots'&&x.body?.operation==='add');
 assert(created,'No account creation API call generated by click');
 assert.strictEqual(created.body.student_id,'2999');
 assert.strictEqual(created.body.class_number,3);
 assert(d.querySelector('#extra-slot-status').textContent.includes('追加しました'),'No success message');
 // Test debt forgiveness with NO amount entered; HTML must not block submit.
 d.querySelector('#funds-kind').value='forgive';
 d.querySelector('#funds-kind').dispatchEvent(new w.Event('input',{bubbles:true}));
 d.querySelector('#funds-target').value='2101';
 d.querySelector('#funds-target').dispatchEvent(new w.Event('input',{bubbles:true}));
 assert(!d.querySelector('#funds-amount').required,'Forgiveness should not require amount');
 form=d.querySelector('#funds-form');
 const debtSubmit=d.querySelector('#funds-submit');
 form.dispatchEvent(new w.SubmitEvent('submit',{bubbles:true,cancelable:true,submitter:debtSubmit}));
 await tick();
 const preview=requests.find(x=>x.path==='funds-extra'&&x.body?.action==='preview');
 assert(preview,'Debt preview API was not called');
 assert(!d.querySelector('#funds-confirm').hidden,'Debt confirmation is not shown');
 d.querySelector('#funds-apply').click();
 await tick();
 const applied=requests.find(x=>x.path==='funds-extra'&&x.body?.action==='apply');
 assert(applied,'Debt apply API was not called');
 assert.strictEqual(applied.body.student_id,'2101');
 assert(d.querySelector('#funds-status').textContent.includes('帳消し完了'),'No debt operation completion message');
 assert.deepStrictEqual(fail,[],fail.join('\n'));
 console.log('PASS: DOM actual fund forgiveness confirmation/apply and extra student ID create via user submit');
 dom.window.close();
}
main().catch(e=>{console.error(e);dom.window.close();process.exit(1)});
